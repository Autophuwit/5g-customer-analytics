------------------------------------------------------------------------------------------
-- MAKE A MASTER 5G CELL SITE
------------------------------------------------------------------------------------------
DROP TABLE IF EXISTS  MT_DIMCS;
CREATE LOCAL TEMP TABLE MT_DIMCS ON COMMIT PRESERVE ROWS AS 
(
WITH  X AS 
(
SELECT  STD_SITE_REF
   , MAX(DECODE(SYSTEM_TYPE, '5G', 1, 0))     IS_SITE_5G
FROM  EDW2.MAST_CELL_SITE
WHERE  1 = 1
   AND STD_SITE_REF IS NOT NULL
GROUP BY 1
) 
,   A AS
(
SELECT  STD_SITE_REF
   , CCAATT_CD
   , SUM(1)  CNT
FROM  EDW2.MAST_CELL_SITE
WHERE  1 = 1
   AND CCAATT_CD IS NOT NULL
GROUP BY 1,2
LIMIT  1 OVER (PARTITION BY STD_SITE_REF ORDER BY CNT DESC)
)
,   B AS
(
SELECT  STD_SITE_REF
   , STD_SITE_NM
   , SUM(1)  CNT
FROM  EDW2.MAST_CELL_SITE
WHERE  1 = 1
   AND STD_SITE_NM IS NOT NULL
GROUP BY 1,2
LIMIT  1 OVER (PARTITION BY STD_SITE_REF ORDER BY CNT DESC)
)
,   C AS
(
SELECT  IMPACTED_SITE           STD_SITE_NM
   , MIN(DECODE(PRIORITY, 'P0', 0, 'P1', 1, 'P2', 2, 3)) PRIORITY
   , MIN(END_DT)           PRIORITY_AS_OF
FROM  SANDBOX2.NTWK_IMPACTED_SITE_V2
WHERE  1 = 1
   AND END_DT = ( SELECT  MIN(END_DT) 
        FROM   SANDBOX2.NTWK_IMPACTED_SITE_V2 
        WHERE   1 = 1
           AND TO_CHAR(END_DT,'YYYYMM')::INT > :RUN_MNTH
       )
GROUP BY 1
)
 
SELECT  X.STD_SITE_REF
   , COALESCE(UPPER(EDW2.CLSTR_MAST.PO_ZONE_EN),'')     REGION_EN
   , COALESCE(UPPER(EDW2.CLSTR_MAST.PROVINCE_EN),'')     PROVINCE_EN
   , COALESCE(UPPER(EDW2.CLSTR_MAST.AMPHUR_EN),'')     AMPHUR_EN
   , COALESCE(UPPER(EDW2.CLSTR_MAST.TUMBON_EN),'')     TUMBON_EN
   , X.IS_SITE_5G
   , COALESCE(DECODE(C.PRIORITY, 3, '', 'P' || C.PRIORITY),'') PRIORITY
   , C.PRIORITY_AS_OF
FROM  X
LEFT JOIN A   ON X.STD_SITE_REF = A.STD_SITE_REF
LEFT JOIN B   ON X.STD_SITE_REF = B.STD_SITE_REF
LEFT JOIN C   ON B.STD_SITE_NM = C.STD_SITE_NM
LEFT JOIN EDW2.CLSTR_MAST ON A.CCAATT_CD = EDW2.CLSTR_MAST.PROVINCE_CD || EDW2.CLSTR_MAST.AMPHUR_CD || EDW2.CLSTR_MAST.TUMBON_CD
 
)
SEGMENTED BY HASH(STD_SITE_REF) ALL NODES
;


------------------------------------------------------------------------------------------
-- ADD 5G SUPPORT FLAG TO THE TABLE
------------------------------------------------------------------------------------------
ALTER TABLE SANDBOX2.AUTO_5G_PROFILE_NEW
ADD COLUMN SUPPORT_SITE_5G VARCHAR(20);


UPDATE SANDBOX2.AUTO_5G_PROFILE_NEW A
SET SUPPORT_SITE_5G =
    CASE
        WHEN COALESCE(B.IS_SITE_5G, 0) = 1 THEN 'SUPPORT5G'
        ELSE 'NOT_SUPPORT5G'
    END
FROM MT_DIMCS B
WHERE A.STD_SITE_REF = B.STD_SITE_REF;

------------------------------------------------------------------------------------------
-- LOAD GUARD + SWAP
--   replace the current table only if the new one is not empty and has >= 90% of its rows;
--   otherwise LOAD_OK = 1 / 0 raises "division by zero" and the script stops (ON_ERROR_STOP),
--   so the reports keep reading last month's AUTO_5G_PROFILE
--   first run ever: rename AUTO_5G_PROFILE_NEW to AUTO_5G_PROFILE by hand
------------------------------------------------------------------------------------------
SELECT N.NEW_ROWS
, C.CUR_ROWS
, 1 / (CASE WHEN N.NEW_ROWS > 0 AND N.NEW_ROWS >= 0.9 * C.CUR_ROWS THEN 1 ELSE 0 END) AS LOAD_OK
FROM (SELECT COUNT(*) AS NEW_ROWS FROM SANDBOX2.AUTO_5G_PROFILE_NEW) N
CROSS JOIN (SELECT COUNT(*) AS CUR_ROWS FROM SANDBOX2.AUTO_5G_PROFILE) C
;

DROP TABLE IF EXISTS SANDBOX2.AUTO_5G_PROFILE_OLD;

-- one statement: readers never see the table missing; last month stays in _OLD for a quick roll-back
ALTER TABLE SANDBOX2.AUTO_5G_PROFILE, SANDBOX2.AUTO_5G_PROFILE_NEW
RENAME TO AUTO_5G_PROFILE_OLD, AUTO_5G_PROFILE;

