------------------------------------------------------------------------------------------
-- 5G PROFILE WITH MOST-USED CELL SITE
--   run:   vsql -v RUN_MNTH=202512 -v ON_ERROR_STOP=on -f 02_5g_profile_cell_site_prioritisation.sql
--   needs: SANDBOX2.V_5G_SUBR_FLAG_MNTH (00_5g_subr_flag_view.sql)
--   ON_ERROR_STOP matters: the load guard before the table swap stops the script on a bad load
------------------------------------------------------------------------------------------

------------------------------------------------------------------------------------------
-- RUN DATE
------------------------------------------------------------------------------------------
DROP TABLE IF EXISTS TEMP_MAST_CLDR;

CREATE LOCAL TEMP TABLE TEMP_MAST_CLDR ON COMMIT PRESERVE ROWS AS 
(

SELECT GREG_MTH_ID AS MNTH_ID
, MAX(GREG_DT_DT) AS MAX_RUN_DATE

FROM EDW2.GEOG_CLDR
WHERE GREG_MTH_ID = :RUN_MNTH /* passed in: vsql -v RUN_MNTH=yyyymm */
GROUP BY 1

)
SEGMENTED BY HASH(MNTH_ID) ALL NODES
;

------------------------------------------------------------------------------------------
-- DEDUPLICATE THE RUN MONTH OF EDW2.SNP_MNTH_SUBR_ANLS
------------------------------------------------------------------------------------------
DROP TABLE IF EXISTS TEMP_SNP_MNTH_SUBR_ANLS;

CREATE LOCAL TEMP TABLE TEMP_SNP_MNTH_SUBR_ANLS ON COMMIT PRESERVE ROWS AS
(

SELECT *
FROM EDW2.SNP_MNTH_SUBR_ANLS
WHERE MNTH_ID IN (SELECT MNTH_ID FROM TEMP_MAST_CLDR)
LIMIT 1 OVER (PARTITION BY MNTH_ID, SUBR_ID ORDER BY MOST_USED_4W_CELL_SITE DESC)

)
SEGMENTED BY HASH(MNTH_ID, SUBR_ID) ALL NODES
;

------------------------------------------------------------------------------------------
-- 5G FLAGS (DEVICE / PROVISIONING / USAGE) FROM THE SHARED VIEW
------------------------------------------------------------------------------------------
DROP TABLE IF EXISTS TEMP_SUBR_5G_FLAG; 

CREATE LOCAL TEMP TABLE TEMP_SUBR_5G_FLAG ON COMMIT PRESERVE ROWS AS 
(

SELECT MNTH_ID
, SUBR_ID
, DVC_SUPPORT_FLAG
, PROVISIONING_5G_FLAG
, USAGE_5G_FLAG

FROM SANDBOX2.V_5G_SUBR_FLAG_MNTH
WHERE MNTH_ID IN (SELECT MNTH_ID FROM TEMP_MAST_CLDR)

)
SEGMENTED BY HASH(MNTH_ID, SUBR_ID) ALL NODES
;

------------------------------------------------------------------------------------------
-- MAKE A LOCATION MASTER
------------------------------------------------------------------------------------------
DROP TABLE IF EXISTS  TEMP_LOCATION_MASTER;
CREATE LOCAL TEMP TABLE TEMP_LOCATION_MASTER ON COMMIT PRESERVE ROWS AS 
(
SELECT   COALESCE(STD_SITE_REF,'unknown') LOCATION_ID
  , CASE WHEN COALESCE(STD_SITE_REF,'unknown') = 'unknown'
    THEN 'unknown'
    ELSE PROVINCE_EN
    END PROVINCE_EN
  , CASE WHEN COALESCE(STD_SITE_REF,'unknown') = 'unknown'
    THEN 'unknown'
    ELSE AMPHUR_EN
    END AMPHUR_EN
  , CASE WHEN COALESCE(STD_SITE_REF,'unknown') = 'unknown'
    THEN 'unknown'
    ELSE TUMBON_EN
    END TUMBON_EN
FROM      EDW2.MAST_CELL_SITE
LIMIT  1 OVER (PARTITION BY LOCATION_ID ORDER BY DW_LAST_UPDATE_TIME DESC)
)
SEGMENTED BY HASH(LOCATION_ID) ALL NODES
;

DROP TABLE IF EXISTS  TEMP_REGION_MASTER;
CREATE LOCAL TEMP TABLE TEMP_REGION_MASTER ON COMMIT PRESERVE ROWS AS 
(
SELECT 
	  PROVINCE_EN
	, AMPHUR_EN
	, TUMBON_EN
	, PP_ZONE_EN 
FROM EDW2.CLSTR_MAST 
WHERE PROVINCE_EN <> 'unknown' 
GROUP BY 1,2,3,4 
)
SEGMENTED BY HASH(PROVINCE_EN) ALL NODES
;

DROP TABLE IF EXISTS  TEMP_MOST_USE_LOCATION;
CREATE LOCAL TEMP TABLE TEMP_MOST_USE_LOCATION ON COMMIT PRESERVE ROWS AS 
(
SELECT 
	  A.MNTH_ID
	, A.SUBR_ID
	, F.STD_SITE_REF
	, G.PROVINCE_EN
	, G.AMPHUR_EN
	, G.TUMBON_EN
	, H.PP_ZONE_EN 
FROM TEMP_SNP_MNTH_SUBR_ANLS AS A
LEFT OUTER JOIN EDW2_MN.BNIC_MOST_USE_CSITE_MNTH AS F
ON A.SUBR_ID = F.ROOT_SBSCRPN_ID
AND A.MNTH_ID = F.KEY_MNTH
LEFT OUTER JOIN TEMP_LOCATION_MASTER AS G
ON F.STD_SITE_REF = G.LOCATION_ID
LEFT OUTER JOIN TEMP_REGION_MASTER AS H
ON G.PROVINCE_EN = H.PROVINCE_EN
AND G.AMPHUR_EN =   H.AMPHUR_EN 
AND	G.TUMBON_EN =  	H.TUMBON_EN
LIMIT 1 OVER (PARTITION BY MNTH_ID, SUBR_ID ORDER BY STD_SITE_REF)
)
SEGMENTED BY HASH(MNTH_ID, SUBR_ID) ALL NODES
;

DROP TABLE IF EXISTS  TEMP_CHURN_SCORE;
CREATE LOCAL TEMP TABLE TEMP_CHURN_SCORE ON COMMIT PRESERVE ROWS AS 
(
SELECT DISTINCT
	  ROOT_SBSCRPN_ID
	, KEY_MNTH
	, SCORE
	, CRTD_BY 
FROM EDW2_MN.PO_CREDIT_SCOR
WHERE KEY_MNTH IN (SELECT MNTH_ID FROM TEMP_MAST_CLDR)
)
SEGMENTED BY HASH(KEY_MNTH, ROOT_SBSCRPN_ID) ALL NODES
;



